// 用 @vibeslash/core 的数据生成 README（中文）和 README.en/ja/ko.md 里的指令大全表格，保证文档和产品里的数据一致。
// 用法：node scripts/readme.ts（写入）；node scripts/readme.ts --check（只检查是否最新，CI 用）
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CLIENT_IDS,
  SURFACE_LABELS_I18N,
  availableIn,
  clientIn,
  type ClientId,
  type Command,
  type Locale,
} from '../packages/core/src/index.ts';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** 表头和备注里的固定文字 */
interface Labels {
  file: string;
  head: [string, string, string];
  skill: string;
  workflow: string;
  webArg: string;
  webNo: string;
  only: (surfaces: string[]) => string;
  aliases: string;
  generated: string;
}

const LABELS: Record<Locale, Labels> = {
  'zh-CN': {
    file: 'README.md',
    head: ['指令', '作用', '备注'],
    skill: '内置技能',
    workflow: '内置工作流',
    webArg: '网页版需带参数',
    webNo: '网页版不可用',
    only: (s) => `仅${s.join('、')}`,
    aliases: '别名',
    generated: '由 scripts/readme.ts 生成，请勿手改',
  },
  en: {
    file: 'README.en.md',
    head: ['Command', 'What it does', 'Notes'],
    skill: 'Built-in skill',
    workflow: 'Built-in workflow',
    webArg: 'Needs an argument on the web',
    webNo: 'Not available on the web',
    only: (s) => `${s.join(', ')} only`,
    aliases: 'Aliases',
    generated: 'Generated by scripts/readme.ts; do not edit by hand',
  },
  ja: {
    file: 'README.ja.md',
    head: ['コマンド', '働き', '備考'],
    skill: '組み込みスキル',
    workflow: '組み込みワークフロー',
    webArg: 'Web 版では引数が必要',
    webNo: 'Web 版では使用不可',
    only: (s) => `${s.join('・')}のみ`,
    aliases: '別名',
    generated: 'scripts/readme.ts で生成。手で編集しないでください',
  },
  ko: {
    file: 'README.ko.md',
    head: ['명령어', '기능', '비고'],
    skill: '내장 스킬',
    workflow: '내장 워크플로',
    webArg: '웹에서는 인수 필요',
    webNo: '웹에서 사용 불가',
    only: (s) => `${s.join(', ')}에서만`,
    aliases: '별칭',
    generated: 'scripts/readme.ts로 생성됨. 직접 수정하지 마세요',
  },
};

function notes(locale: Locale, clientId: ClientId, cmd: Command): string {
  const l = LABELS[locale];
  const client = clientIn(clientId, locale);
  const list: string[] = [];
  if (cmd.kind === 'skill') list.push(l.skill);
  if (cmd.kind === 'workflow') list.push(l.workflow);
  if (clientId === 'claude-code') {
    if (cmd.limits?.web === 'arg') list.push(l.webArg);
    if (cmd.limits?.web === 'no') list.push(l.webNo);
  } else {
    const where = client.surfaces.filter((s) => availableIn(cmd, client, s));
    if (where.length < client.surfaces.length) list.push(l.only(where.map((s) => SURFACE_LABELS_I18N[locale][s])));
  }
  if (cmd.aliases?.length) list.push(`${l.aliases} ${cmd.aliases.map((a) => `\`/${a}\``).join(' ')}`);
  return list.join(locale === 'zh-CN' ? '；' : '; ');
}

function table(locale: Locale, clientId: ClientId): string {
  const client = clientIn(clientId, locale);
  const [a, b, c] = LABELS[locale].head;
  const sections = [];
  for (const cat of client.categories) {
    const rows = client.commands
      .filter((cmd) => cmd.cat === cat.key)
      .map((cmd) => {
        const sig = cmd.args ? `/${cmd.name} ${cmd.args}` : `/${cmd.name}`;
        return `| \`${cell(sig)}\` | ${cell(cmd.desc)} | ${cell(notes(locale, clientId, cmd))} |`;
      });
    if (rows.length) sections.push([`#### ${cat.label}`, '', `| ${a} | ${b} | ${c} |`, '| :- | :- | :- |', ...rows].join('\n'));
  }
  return sections.join('\n\n');
}

const check = process.argv.includes('--check');
let stale = false;
for (const locale of Object.keys(LABELS) as Locale[]) {
  const { file, generated: note } = LABELS[locale];
  const readmePath = path.join(root, file);
  let readme = fs.readFileSync(readmePath, 'utf8');
  const original = readme;
  for (const id of CLIENT_IDS) {
    const start = `<!-- commands:${id}:start -->`;
    const end = `<!-- commands:${id}:end -->`;
    const from = readme.indexOf(start);
    const to = readme.indexOf(end);
    if (from < 0 || to < from) {
      console.error(`${file} 里没有找到 ${start} … ${end} 标记`);
      process.exit(1);
    }
    const generated = `${start}\n<!-- ${note} -->\n\n${table(locale, id)}\n\n${end}`;
    readme = readme.slice(0, from) + generated + readme.slice(to + end.length);
  }
  if (readme === original) continue;
  if (check) {
    console.error(`${file} 的指令表格不是最新的，请运行 pnpm readme`);
    stale = true;
  } else {
    fs.writeFileSync(readmePath, readme);
    console.log(`已更新 ${file} 的指令表格`);
  }
}
if (stale) process.exit(1);
if (check) console.log('README 的指令表格都是最新的');
